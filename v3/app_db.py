"""PostgreSQL storage for the app's own data: secrets, workflows, runs, their log events, and the learned-steps cache."""

import atexit
import json
import logging
import queue
import threading
import time
from contextlib import contextmanager
from datetime import datetime, timezone
from typing import Any, Iterator, Optional

import psycopg
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

from config import DATABASE_URL

logger = logging.getLogger(__name__)

# Raised when a unique rule is broken, for example two secrets with the same label
IntegrityError = psycopg.errors.IntegrityError

# Everything is created on startup if missing. Row-level security is switched on with no policies, so the
# public (anon) key of a Supabase project can never read these tables; only the direct connection can.
_SCHEMA = """
CREATE TABLE IF NOT EXISTS secrets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label       TEXT NOT NULL UNIQUE,
    kind        TEXT NOT NULL,            -- 'llm_key' | 'db_credential'
    ciphertext  BYTEA NOT NULL,           -- encrypted JSON; never returned by the API
    last4       TEXT,                     -- for the masked preview only
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS workflows (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL UNIQUE,
    target_url          TEXT NOT NULL,
    master_prompt       TEXT NOT NULL DEFAULT '',
    task_prompt         TEXT NOT NULL DEFAULT '',
    match_key           TEXT NOT NULL DEFAULT '',
    model_name          TEXT NOT NULL,
    llm_secret_id       BIGINT REFERENCES secrets(id),
    db_secret_id        BIGINT REFERENCES secrets(id),
    use_cache           INTEGER NOT NULL DEFAULT 1,
    max_concurrency     INTEGER NOT NULL DEFAULT 3,
    submit_url_contains TEXT NOT NULL DEFAULT '',
    submit_method       TEXT NOT NULL DEFAULT 'POST',
    verify_kind         TEXT NOT NULL DEFAULT 'none',   -- 'none' | 'table' | 'expected_view'
    verify_config       TEXT NOT NULL DEFAULT '{}',     -- JSON
    reconcile           INTEGER NOT NULL DEFAULT 0,
    headless            INTEGER NOT NULL DEFAULT 0,     -- 1 = run the browser without a visible window
    data_json           TEXT NOT NULL DEFAULT '[]',     -- the latest uploaded records
    cache_epoch         INTEGER NOT NULL DEFAULT 1,     -- bump to forget the learned steps
    created_at          TEXT NOT NULL,
    updated_at          TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS runs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id    BIGINT NOT NULL,
    workflow_name  TEXT NOT NULL,           -- name at the time of the run
    status         TEXT NOT NULL,           -- running | verifying | done | error | aborted
    total          INTEGER NOT NULL DEFAULT 0,
    error          TEXT,
    report_json    TEXT,                    -- the BatchReport, once verified
    created_at     TEXT NOT NULL,
    finished_at    TEXT
);

CREATE TABLE IF NOT EXISTS run_events (
    run_id       BIGINT NOT NULL,
    seq          BIGINT NOT NULL,           -- increasing per run; the Logs page asks for "everything after N"
    at           TEXT NOT NULL,
    type         TEXT NOT NULL,
    payload_json TEXT NOT NULL,
    PRIMARY KEY (run_id, seq)
);

CREATE TABLE IF NOT EXISTS cached_steps (
    workflow_name   TEXT NOT NULL,
    path_variant    TEXT NOT NULL,
    target_key      TEXT NOT NULL,      -- field_name, or "<action_type>::<x_path>" for a click with no field
    step_index      INTEGER NOT NULL,   -- ordering hint only (not part of row identity)
    action_offset   INTEGER NOT NULL,
    action_type     TEXT NOT NULL,      -- 'click' | 'input' | 'select_dropdown'
    field_name      TEXT,               -- which record field this step's value maps to (NULL for click-only steps)
    instruction     TEXT,               -- diagnostic: agent's own next_goal text when this step was captured
    x_path          TEXT NOT NULL,
    node_name       TEXT,
    attributes_json TEXT NOT NULL,
    stable_hash     TEXT,
    fingerprint     TEXT NOT NULL,
    updated_at      TEXT NOT NULL,
    PRIMARY KEY (workflow_name, path_variant, target_key)
);

CREATE TABLE IF NOT EXISTS run_metrics (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_name     TEXT NOT NULL,
    path_variant      TEXT NOT NULL,
    record_id         TEXT NOT NULL,
    mode              TEXT NOT NULL,
    started_at        TEXT NOT NULL,
    finished_at       TEXT NOT NULL,
    cache_hits        INTEGER NOT NULL DEFAULT 0,
    cache_misses      INTEGER NOT NULL DEFAULT 0,
    llm_steps         INTEGER NOT NULL DEFAULT 0,
    miss_reasons_json TEXT
);

-- What the AI did on one record, kept so a repeatable recipe can be learned from several of them
CREATE TABLE IF NOT EXISTS recipe_traces (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_name   TEXT NOT NULL,
    path_variant    TEXT NOT NULL,
    record_id       TEXT NOT NULL,
    fields_json     TEXT NOT NULL,
    trace_json      TEXT NOT NULL,
    created_at      TEXT NOT NULL
);

-- The learned recipe for a workflow and variant (one row each)
CREATE TABLE IF NOT EXISTS recipes (
    workflow_name   TEXT NOT NULL,
    path_variant    TEXT NOT NULL,
    recipe_json     TEXT NOT NULL,
    created_at      TEXT NOT NULL,
    PRIMARY KEY (workflow_name, path_variant)
);

-- Columns added after the first release: safe to run every time
ALTER TABLE workflows ADD COLUMN IF NOT EXISTS headless INTEGER NOT NULL DEFAULT 0;

-- Lock the tables away from Supabase's public API roles (they do not exist on a plain Postgres)
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['secrets','workflows','runs','run_events','cached_steps','run_metrics','recipe_traces','recipes'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON %I FROM anon', t);
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
      EXECUTE format('REVOKE ALL ON %I FROM authenticated', t);
    END IF;
  END LOOP;
END $$;
"""

_pool: Optional[ConnectionPool] = None
_pool_lock = threading.Lock()


# Returns the current time as an ISO string in UTC.
# Takes nothing; used for created_at / updated_at columns.
def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


# Opens the connection pool on first use and makes sure the tables exist.
# Takes nothing; raises RuntimeError with the next step when DATABASE_URL is missing or the database cannot be reached.
def _get_pool() -> ConnectionPool:
    global _pool
    if _pool is not None:
        return _pool
    with _pool_lock:
        if _pool is not None:
            return _pool
        if not DATABASE_URL:
            raise RuntimeError(
                "DATABASE_URL is not set. Create a Supabase project, copy its connection string into v3/.env "
                "as DATABASE_URL=..., and restart (steps are in README.md)."
            )
        # prepare_threshold=None: Supabase's pooler in transaction mode does not support prepared statements
        pool = ConnectionPool(
            DATABASE_URL,
            min_size=1,
            max_size=10,
            kwargs={"row_factory": dict_row, "prepare_threshold": None},
            open=False,
            # Supabase's pooler drops idle connections; test one before handing it out and drop old idle ones
            check=ConnectionPool.check_connection,
            max_idle=120,
        )
        try:
            pool.open(wait=True, timeout=20)
            with pool.connection() as conn:
                conn.execute(_SCHEMA)
        except Exception as exc:
            pool.close()
            raise RuntimeError(f"Could not connect to the database from DATABASE_URL: {exc}") from exc
        _pool = pool
        return _pool


# The result of one query: rows as plain dicts, like the old SQLite rows.
class _Result:
    def __init__(self, cursor: psycopg.Cursor) -> None:
        self._cursor = cursor
        self.rowcount = cursor.rowcount

    def fetchone(self) -> Optional[dict[str, Any]]:
        return self._cursor.fetchone()

    def fetchall(self) -> list[dict[str, Any]]:
        return self._cursor.fetchall()


# One database connection inside a transaction; SQL is written with `?` placeholders.
class _Conn:
    def __init__(self, raw: psycopg.Connection) -> None:
        self._raw = raw

    # Runs one statement with its parameters; returns a result with fetchone / fetchall / rowcount.
    # To get an inserted row's id, end the statement with RETURNING id and read it from fetchone().
    def execute(self, sql: str, params: tuple | list = ()) -> _Result:
        return _Result(self._raw.execute(sql.replace("?", "%s"), params))


# Yields a connection that commits on success, rolls back on error and always goes back to the pool.
# `write` is accepted for older call sites; Postgres handles concurrent writers itself.
@contextmanager
def db(write: bool = False) -> Iterator[_Conn]:
    with _get_pool().connection() as raw:
        yield _Conn(raw)


# Marks runs left "running" by a previous server process as failed, so the UI never shows a ghost run.
# Takes nothing; called once at startup (this is also the first database touch, so it fails fast if the URL is wrong).
def mark_orphaned_runs() -> int:
    with db() as conn:
        return conn.execute(
            "UPDATE runs SET status='error', error='Server restarted while this run was in progress', finished_at=? "
            "WHERE status IN ('running', 'verifying')",
            (now_iso(),),
        ).rowcount


# ---------------------------------------------------------------- log events
# Events are written by a background thread in small batches, so a slow network round trip to the database
# never holds up the browser agent. flush_events() waits until everything queued has been stored.

_events: "queue.Queue[tuple[int, int, str, str, str]]" = queue.Queue()
_event_seq: dict[int, int] = {}
_event_lock = threading.Lock()
_writer: Optional[threading.Thread] = None


# Stores queued events in batches until the process ends; retries if the database is briefly unreachable.
def _write_events_forever() -> None:
    while True:
        batch = [_events.get()]
        deadline = time.monotonic() + 0.3
        while len(batch) < 200:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                break
            try:
                batch.append(_events.get(timeout=remaining))
            except queue.Empty:
                break
        while True:
            try:
                with _get_pool().connection() as raw:
                    with raw.cursor() as cur:
                        cur.executemany(
                            "INSERT INTO run_events (run_id, seq, at, type, payload_json) VALUES (%s, %s, %s, %s, %s) "
                            "ON CONFLICT (run_id, seq) DO NOTHING",
                            batch,
                        )
                break
            except Exception:  # noqa: BLE001 - never lose events to a blip; try again shortly
                logger.exception("Could not store %s log event(s); retrying in 2 s", len(batch))
                time.sleep(2)
        for _ in batch:
            _events.task_done()


# Starts the background writer the first time an event is queued.
def _ensure_writer() -> None:
    global _writer
    with _event_lock:
        if _writer is None:
            _writer = threading.Thread(target=_write_events_forever, daemon=True, name="event-writer")
            _writer.start()


# Queues one log event for a run, numbering it after the run's latest event; returns the sequence number.
# Takes the run id, the event type and the payload dict.
def append_event(run_id: int, event_type: str, payload: dict[str, Any]) -> int:
    with _event_lock:
        if run_id not in _event_seq:
            with db() as conn:
                row = conn.execute("SELECT COALESCE(MAX(seq), 0) AS last FROM run_events WHERE run_id=?", (run_id,)).fetchone()
            _event_seq[run_id] = row["last"]
        _event_seq[run_id] += 1
        seq = _event_seq[run_id]
    _ensure_writer()
    _events.put((run_id, seq, now_iso(), event_type, json.dumps(payload, default=str)))
    return seq


# Waits until every queued event has been written to the database.
# Takes nothing; call it before marking a run finished so its last events are visible with the final status.
def flush_events() -> None:
    if _writer is not None:
        _events.join()


# Closes the connection pool when the process ends (registered first, so it runs after the final flush)
def _close_pool() -> None:
    if _pool is not None:
        _pool.close()


atexit.register(_close_pool)
atexit.register(flush_events)


# Returns a run's events with a sequence number above `after`, oldest first.
# Takes the run id and the last sequence the caller has seen; returns a list of event dicts.
def events_after(run_id: int, after: int = 0, limit: int = 2000) -> list[dict[str, Any]]:
    with db() as conn:
        rows = conn.execute(
            "SELECT seq, at, type, payload_json FROM run_events WHERE run_id=? AND seq>? ORDER BY seq LIMIT ?",
            (run_id, after, limit),
        ).fetchall()
    return [{"seq": r["seq"], "at": r["at"], "type": r["type"], **json.loads(r["payload_json"])} for r in rows]
