-- Credit Desk: a test site for terminautomator (retailers ask for credit; an agent decides).
-- retailers = the ledger the agent must look up; credit_requests = what it decides on;
-- credit_requests_expected = the ground truth, never shown in the UI.

create table public.retailers (
  id bigint generated by default as identity primary key,
  name text not null,
  city text not null,
  credit_term_days integer not null check (credit_term_days in (30, 60, 90)),
  credit_limit numeric not null,
  outstanding_amount numeric not null default 0,
  -- stored as a number (not a date) so the expected decision never drifts over time
  days_since_last_payment integer not null,
  is_blocked boolean not null default false,
  unique (name, city)
);

create table public.credit_requests (
  id bigint generated by default as identity primary key,
  retailer_name text not null,
  retailer_city text not null,
  request_date date not null,
  requested_amount numeric not null,
  note text,
  -- written by whoever clicks the buttons; null = not decided yet
  decision text check (decision in ('approve', 'reject', 'hold')),
  decided_at timestamptz
);

-- Ground truth. Retailer match is exact on name + city (case/space-insensitive); a near-miss name is "not found".
-- Each request is judged on its own against the ledger (approving one does not change outstanding).
--   not found -> hold | blocked -> reject | overdue (days > term) -> reject
--   outstanding + requested <= limit -> approve | <= limit * 1.10 -> hold | else reject
create view public.credit_requests_expected as
select
  q.id as request_id,
  q.retailer_name,
  q.retailer_city,
  q.requested_amount,
  case
    when r.id is null then 'hold'
    when r.is_blocked then 'reject'
    when r.days_since_last_payment > r.credit_term_days then 'reject'
    when r.outstanding_amount + q.requested_amount <= r.credit_limit then 'approve'
    when r.outstanding_amount + q.requested_amount <= r.credit_limit * 1.10 then 'hold'
    else 'reject'
  end as expected_decision
from public.credit_requests q
left join public.retailers r
  on lower(trim(r.name)) = lower(trim(q.retailer_name))
 and lower(trim(r.city)) = lower(trim(q.retailer_city));

